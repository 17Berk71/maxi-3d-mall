const COUNTRIES = ['Россия', 'Китай', 'Вьетнам', 'Турция', 'Узбекистан', 'Беларусь'];

export function describe(p, model) {
  const t = T[model] || T.box;
  const r = mulberry([...(p.id || p.name)].reduce((a, c) => a * 31 + c.charCodeAt(0) | 0, 7));
  const specs = [['Цвет', colorName(p.color)], ...t[1], ['Страна', COUNTRIES[Math.floor(r() * COUNTRIES.length)]],
    ['Артикул', String(100000 + Math.floor(r() * 899999))]];
  const rating = (4.3 + r() * 0.6).toFixed(1), reviews = 5 + Math.floor(r() * 240);
  return {text: t[0], specs, rating, reviews};
}
