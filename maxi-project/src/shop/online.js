// Какие магазины имеют смысл в онлайне.
// 'shop' — товары можно смотреть и заказывать (одежда, обувь, техника, косметика, дом, мебель, дети);
// 'info' — онлайн-заказа нет, позже здесь будут меню или контакты (кафе, услуги, развлечения, кино);
// 'none' — не показываем ни товаров, ни меню (автоматы, туалеты, администрация, безымянные помещения).

const INFO_WHAT = new Set([
  // еда навынос и в зале, продукты на развес
  'Кофейня', 'Кофе с собой', 'Кафе', 'Ресторан', 'Бургеры', 'Курица', 'Пиццерия', 'Суши', 'Блины', 'Пекарня', 'Мороженое',
  'Азиатская кухня', 'Грузинская кухня', 'Индийская кухня', 'Магазин у дома', 'Микрозелень и салаты', 'Чай',
  'Сладости', 'Сухофрукты и орехи',
  // услуги
  'Ателье', 'Банк', 'Груминг', 'Доставка и почта', 'Изготовление ключей', 'Копицентр и печать', 'Печать фото', 'Фотобудка',
  'Фотостудия', 'Турагентство', 'Ювелирная мастерская',
  // развлечения
  'Аттракцион', 'Детские аттракционы', 'Детский развлекательный парк', 'Развлечения', 'Кинотеатр',
]);
const NONE_WHAT = new Set(['Кофейный автомат', 'Игровой автомат', 'Автомат', 'Автомат с жевательной резинкой', 'Вендинговый автомат',
  'Администрация', 'Приём вторсырья', 'Туалет']);
// по названию: аренда пауэрбанков — услуга, а не магазин
const INFO_NAME = new Set(['Бери заряд', 'EnerGo']);
// автоматы с жвачкой стоят и как «сладости», и как «автомат»
const NONE_NAME = new Set(['Gold Gum']);

export function onlineKind(s) {
  if (!s || s.cat === 'tbd' || s.cat === 'wc') return 'none';
  if (NONE_WHAT.has(s.what) || NONE_NAME.has(s.name)) return 'none';
  if (INFO_NAME.has(s.name) || INFO_WHAT.has(s.what) || s.cat === 'serv') return 'info';
  if (s.cat === 'food') return 'info';
  return 'shop';
}
// магазины, про ассортимент которых ничего не известно — нужно уточнить
export const needsCheck = s => onlineKind(s) === 'shop' && (s.what === 'Магазин' || s.what === 'Островок');
