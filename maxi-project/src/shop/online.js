export function onlineActions(s) {
  if (!s || s.cat === 'tbd' || s.cat === 'wc') return [];
  if (NONE_WHAT.has(s.what) || NONE_NAME.has(s.name) || INFO_NAME.has(s.name)) return [];
  if (BY_NAME[s.name]) return BY_NAME[s.name];
  if (BY_WHAT[s.what]) return BY_WHAT[s.what];
  if (INFO_WHAT.has(s.what) || s.cat === 'serv' || s.cat === 'food') return [];
  // остальные магазины — товары; к большинству подходит и подарочный сертификат
  return ['buy'];
}
export function onlineKind(s) {
  if (!s || s.cat === 'tbd' || s.cat === 'wc' || NONE_WHAT.has(s.what) || NONE_NAME.has(s.name)) return 'none';
  const a = onlineActions(s);
  if (a.includes('buy')) return 'shop';
  return a.length ? 'act' : 'info';
}
// магазины, про ассортимент которых ничего не известно — нужно уточнить
export const needsCheck = s => onlineKind(s) === 'shop' && (s.what === 'Магазин' || s.what === 'Островок');
export function onlineText(s) {
  const k = onlineKind(s);
  if (k === 'none') return '';
  if (k === 'info') return 'Онлайн здесь ничего не оформить — оплата на месте. Позже появятся меню и контакты.';
  return 'Онлайн: ' + onlineActions(s).map(a => ACTIONS[a].t.toLowerCase()).join(', ') + '.';
}
