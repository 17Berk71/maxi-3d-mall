def _norm(s):
    return (s or '').lower().replace('ё', 'е').strip()


def _word(w):
    """Шаблон синонима: с начала слова; короткие, до 4 букв (поло, топ, худи) — ещё и целым словом, иначе «поло» находится в «полоску»."""
    n = _norm(w)
    if len(n) <= 4:
        return r'(^|[\s(«"-])' + re.escape(n) + r'(?![а-яa-z])'
    # длинные — по основе: последняя гласная отбрасывается («майка» находит «майки», «кофта» — «кофты»)
    if ' ' not in n and n[-1] in 'аяыиоеуь': n = n[:-1]
    return r'(^|[\s(«"-])' + re.escape(n)


def color_of(wb_name):
    """Название цвета Wildberries → ключ основного цвета или None (тогда цвет определяется по вырезке)."""
    s = _norm(wb_name)
    if not s:
        return None
    best = None
    for stem, key in WB_COLOR.items():
        st = _norm(stem)
        # совпадение по началу любого слова; из нескольких — самая длинная основа («темно-син» раньше «син»)
        if re.search(r'(^|[\s,;/(-])' + re.escape(st), s) and (best is None or len(st) > len(best[0])):
            best = (st, key)
    return best[1] if best else None


def kind_of(subject='', name=''):
    """Предмет Wildberries и название вещи → ключ вида или None (вид неизвестен — вещь уходит на ручную проверку)."""
    subj, nm = _norm(subject), _norm(name)
    for key, (_ru, _g, syn, wb) in KINDS.items():
        if subj and any(_norm(w) == subj for w in wb):
            # «Футболки» с длинным рукавом в названии — это лонгслив
            if key == 'tee' and re.search(r'длинн\w* рукав', nm):
                return 'longsleeve'
            # в «Куртках» и «Жилетах» бывают пуховики: если название называет более точный вид той же группы
            # (он стоит в KINDS раньше), берём его
            g = KINDS[key][1]
            for k2, (_r2, g2, syn2, _w2) in KINDS.items():
                if k2 == key:
                    break
                if g2 == g and any(re.search(_word(w), nm) for w in syn2):
                    return k2
            return key
    for key, (_ru, _g, syn, _wb) in KINDS.items():
        if any(re.search(_word(w), nm) for w in syn):
            return key
    return None


def group_of(kind):
    return KINDS[kind][1] if kind in KINDS else None


